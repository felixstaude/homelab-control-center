"""Update management: policies, jobs, events and rollouts.

Phase F of Operation Evergreen. Five tables, all new — nothing existing is
altered, so this migration is additive and a downgrade is a clean drop.

## Why this is safe to apply to a running installation

Every table is new and every column has either a default or is nullable, so
there is no backfill and no lock on anything being read. The one non-obvious
piece is `ix_update_jobs_one_open_per_host`, a **partial unique index** over
`host_id` where the state is non-terminal — created on an empty table, so it
cannot fail on existing data.

## What `host_update_policies` says by being absent

A host with no row has the default policy, and the default is manual. That
makes the safe behaviour the one needing no migration data: this migration
inserts nothing, so every existing host continues to update only when an
administrator says so. A migration that had to write a policy per host would
be one whose failure mode is "some hosts now update themselves".

## `update_events.id` is a sequence, not a UUID

An append-only log has to be orderable. `created_at` cannot do it, because
PostgreSQL's `now()` is the *transaction* timestamp and several transitions
are written in one transaction — ordering by `(created_at, uuid)` is ordering
by a random number. `GENERATED ALWAYS AS IDENTITY`, so the application cannot
supply one.

## The `updated_at` triggers

`host_update_policies`, `update_jobs` and `update_rollouts` get one each,
using the shared `set_updated_at()` function created by 0002_users.
`update_jobs` needs it most: its state changes on every transition, and an
`updated_at` that moved only when the application remembered to set it is
exactly the column somebody reads to answer "is this stuck".

`update_events` and `update_rollout_members` get none, deliberately —
`update_events` is append-only and has no `updated_at` column at all, and a
rollout member is an assignment that does not change.
"""

